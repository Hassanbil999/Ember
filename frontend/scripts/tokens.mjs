// Generates app/tokens.css from config/theme.tokens.json (single source of truth).
import { readFileSync, writeFileSync } from "node:fs";
const t = JSON.parse(readFileSync(new URL("../../config/theme.tokens.json", import.meta.url)));
const vars = (o) => Object.entries(o).map(([k, v]) => `  --${k}: ${v};`).join("\n");
const css = `/* generated by scripts/tokens.mjs — edit config/theme.tokens.json */
:root, [data-theme="void"] {\n${vars(t.themes.void)}\n  color-scheme: dark;\n}
[data-theme="paper"] {\n${vars(t.themes.paper)}\n  color-scheme: light;\n}
:root {\n  --r-sm: ${t.radius.sm};\n  --r-md: ${t.radius.md};\n  --t-fast: ${t.motion.fast};\n  --t-base: ${t.motion.base};\n  --ease: ${t.motion.ease};\n}
`;
writeFileSync(new URL("../app/tokens.css", import.meta.url), css);
writeFileSync(new URL("../lib/palettes.json", import.meta.url), JSON.stringify(t.palettes, null, 1));
console.log("tokens.css written");
